// Injects the public Firebase config into public/firebase-messaging-sw.js
// at build/dev time, since service workers can't read process.env.
const fs = require('fs');
const path = require('path');

try {
  require('dotenv').config({ path: path.join(__dirname, '..', '.env.local') });
} catch {
  // dotenv not installed — that's fine, Next reads env automatically for the app.
}

const cfg = {
  apiKey: process.env.NEXT_PUBLIC_FIREBASE_API_KEY || '',
  authDomain: process.env.NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN || '',
  projectId: process.env.NEXT_PUBLIC_FIREBASE_PROJECT_ID || '',
  storageBucket: process.env.NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET || '',
  messagingSenderId: process.env.NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID || '',
  appId: process.env.NEXT_PUBLIC_FIREBASE_APP_ID || '',
};

const sw = `/* AUTO-GENERATED by scripts/build-firebase-sw.js — do not edit by hand */
importScripts('https://www.gstatic.com/firebasejs/10.13.0/firebase-app-compat.js');
importScripts('https://www.gstatic.com/firebasejs/10.13.0/firebase-messaging-compat.js');

firebase.initializeApp(${JSON.stringify(cfg, null, 2)});

const messaging = firebase.messaging();

messaging.onBackgroundMessage((payload) => {
  const title = payload.notification?.title || "SpeedJob's";
  const options = {
    body: payload.notification?.body || '',
    icon: '/icon-192.png',
    badge: '/icon-192.png',
    data: payload.data || {},
  };
  self.registration.showNotification(title, options);
});

self.addEventListener('notificationclick', (event) => {
  event.notification.close();
  const jobId = event.notification.data?.job_id;
  const url = jobId ? \`/candidate/job/\${jobId}\` : '/candidate/home';
  event.waitUntil(clients.openWindow(url));
});
`;

const out = path.join(__dirname, '..', 'public', 'firebase-messaging-sw.js');
fs.writeFileSync(out, sw);
if (!cfg.apiKey) {
  console.warn('[build-firebase-sw] NEXT_PUBLIC_FIREBASE_* env not set — SW generated with empty config (FCM disabled).');
} else {
  console.log('[build-firebase-sw] Wrote', path.relative(process.cwd(), out));
}
